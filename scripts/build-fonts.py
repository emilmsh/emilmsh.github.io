"""Regenerate assets/fonts.css: Libertinus faces embedded as base64 woff2.

Reads the OTF sources from TeX Live (found via kpsewhich) and writes one
@font-face rule per face. Run from the repo root:

    python scripts/build-fonts.py

Requires fontTools and brotli (pip install fonttools brotli).
"""
import base64
import io
import pathlib
import subprocess

from fontTools.ttLib import TTFont

# (file, family, weight, style)
FACES = [
    ("LibertinusSerif-Regular.otf", "Libertinus Serif", 400, "normal"),
    ("LibertinusSerif-Italic.otf", "Libertinus Serif", 400, "italic"),
    ("LibertinusSerif-Semibold.otf", "Libertinus Serif", 600, "normal"),
    ("LibertinusSans-Regular.otf", "Libertinus Sans", 400, "normal"),
]

HEADER = """/* Libertinus Serif and Libertinus Sans embedded as base64 data URIs so the
   fonts are part of the render-blocking CSS — available at first paint, no
   FOUT, no swap. Generated by scripts/build-fonts.py — don't edit by hand;
   editable styling lives in style.css. */
"""


def locate(name):
    path = subprocess.run(["kpsewhich", name], capture_output=True, text=True, check=True).stdout.strip()
    if not path:
        raise SystemExit(f"kpsewhich could not find {name}")
    return pathlib.Path(path)


def woff2_b64(path):
    font = TTFont(path)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode("ascii")


out = pathlib.Path(__file__).resolve().parent.parent / "assets" / "fonts.css"
rules = []
for file, family, weight, style in FACES:
    data = woff2_b64(locate(file))
    rules.append(
        f'@font-face{{font-family:"{family}";font-weight:{weight};font-style:{style};'
        f"font-display:block;src:url(data:font/woff2;base64,{data}) format(\"woff2\")}}"
    )
out.write_text(HEADER + "\n".join(rules) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
